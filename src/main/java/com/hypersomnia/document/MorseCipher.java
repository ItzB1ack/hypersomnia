package com.hypersomnia.document;

/** Морзе: латиница, цифры и кириллица (Ё = Е). На листе — кардиограмма (HeartMorse): низкий зубец = точка, высокий = тире. Без клиентских импортов. */
public final class MorseCipher {
    private MorseCipher() {}

    private static final String[] LETTERS = {
            ".-", "-...", "-.-.", "-..", ".", "..-.", "--.", "....", "..", ".---", "-.-", ".-..", "--",
            "-.", "---", ".--.", "--.-", ".-.", "...", "-", "..-", "...-", ".--", "-..-", "-.--", "--.."};
    private static final String[] DIGITS = {"-----", ".----", "..---", "...--", "....-", ".....", "-....", "--...", "---..", "----."};
    /** А Б В Г Д Е Ж З И Й К Л М Н О П Р С Т У Ф Х Ц Ч Ш Щ Ъ Ы Ь Э Ю Я */
    private static final String[] CYRILLIC = {
            ".-", "-...", ".--", "--.", "-..", ".", "...-", "--..", "..", ".---", "-.-", ".-..", "--",
            "-.", "---", ".--.", ".-.", "...", "-", "..-", "..-.", "....", "-.-.", "---.", "----", "--.-",
            "--.--", "-.--", "-..-", "..-..", "..--", ".-.-"};

    /** Код символа или пустая строка, если символа в таблице нет. */
    public static String code(char c) {
        c = Character.toUpperCase(c);
        if (c == '\u0401') c = '\u0415'; // Ё -> Е
        if (c >= 'A' && c <= 'Z') return LETTERS[c - 'A'];
        if (c >= '\u0410' && c <= '\u042F') return CYRILLIC[c - '\u0410'];
        if (c >= '0' && c <= '9') return DIGITS[c - '0'];
        return "";
    }
}